
"""Build the blind adjudication packages for Part 5 (Stage 3).

Reads only committed/provenance-pinned inputs, writes evaluator-facing files
with no labels, no frequency scores and no prior judgments.
Run from the repository root:  python exp/handoff/part5-pilot/build_packages.py
"""

from __future__ import annotations

import hashlib
import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = Path(__file__).resolve().parent / "llm_adjudication"
SEED = 20261117
RETRIEVAL_DATE = "2026-11-08"
STRATA = {
    "score_5": lambda s: s == 5,
    "score_3_4": lambda s: s in (3, 4),
    "score_1_2": lambda s: s in (1, 2),
    "score_0": lambda s: s == 0,
}
TEMPORAL = (
    "The atomic claim comes from a biography generated by GPT-4 for the FActScore "
    "benchmark (2023). The evidence passage was retrieved from English Wikipedia on "
    "2026-11-08. Treat the passage as the 2026 state of the article and flag any claim "
    "whose truth may depend on the date."
)


def subject_of(prompt: str) -> str:
    return prompt.split("bio of", 1)[-1].strip() if "bio of" in prompt else prompt.strip()


def sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def main() -> int:
    raw = json.loads(
        (ROOT / "third_party/conformal-factual-lm/out/factscore_subclaims_with_scores.jsonl")
        .read_text(encoding="utf-8")
    )["data"]
    split = json.loads((ROOT / "data/splits/factscore.json").read_text(encoding="utf-8"))["splits"]
    byid = {f"factscore-{i:04d}": r for i, r in enumerate(raw)}

    cache_dir = ROOT / "data/wiki_cache"
    evidence = {}
    sources = {}
    for pid in byid:
        subj = subject_of(byid[pid]["prompt"])
        if subj in evidence:
            continue
        path = cache_dir / (subj.replace(" ", "_") + ".json")
        if not path.exists():
            evidence[subj] = {"title": subj, "extract": "", "available": False}
            continue
        blob = json.loads(path.read_text(encoding="utf-8"))
        text = blob.get("extract", "")
        evidence[subj] = {"title": blob.get("title") or subj, "extract": text, "available": bool(text)}
        sources[subj] = {
            "subject": subj,
            "title": evidence[subj]["title"],
            "url": "https://en.wikipedia.org/wiki/" + (blob.get("title") or subj).replace(" ", "_"),
            "retrieval_date": RETRIEVAL_DATE,
            "revision_id": None,
            "chars": len(text),
            "extract_sha256": sha256(text),
            "stub_under_2000_chars": len(text) < 2000,
            "cache_file": str(path.relative_to(ROOT)),
        }

    rows = []
    rows_all = []
    for pid in byid:
        subj = subject_of(byid[pid]["prompt"])
        for idx, c in enumerate(byid[pid]["claims"]):
            row = {
                "pid": pid,
                "subject": subj,
                "claim_index": idx,
                "claim": c["subclaim"],
                "score": int(c["frequency-score"]),
                "_annotation": c["annotation"],
            }
            rows_all.append(row)
            if pid in split["test"]:
                rows.append(row)

    rng = random.Random(SEED)
    main_ids, pilot_ids = [], []
    for name, pred in STRATA.items():
        pool = sorted((r for r in rows if pred(r["score"])), key=lambda r: (r["pid"], r["claim_index"]))
        rng.shuffle(pool)
        if len(pool) < 20:
            raise SystemExit(f"stratum {name} has only {len(pool)} test claims")
        take_main = pool[:20]
        main_ids.extend(take_main)
        taken = {(r["pid"], r["claim_index"]) for r in take_main}
        # The test set alone has only 21 score-0 claims, so the 3-per-stratum pilot
        # is drawn from all 50 biographies. It tests protocol adherence, not the
        # population, and is reported separately from the 80-claim batch.
        wide = sorted((r for r in rows_all if pred(r["score"])), key=lambda r: (r["pid"], r["claim_index"]))
        rng.shuffle(wide)
        take_pilot = [r for r in wide if (r["pid"], r["claim_index"]) not in taken][:3]
        if len(take_pilot) < 3:
            raise SystemExit(f"stratum {name} has too few claims for the pilot")
        pilot_ids.extend(take_pilot)

    def blind(record, blind_id):
        subj = record["subject"]
        ev = evidence[subj]
        return {
            "blind_id": blind_id,
            "claim": record["claim"],
            "evidence_title": ev["title"],
            "evidence_text": ev["extract"],
            "evidence_available": ev["available"],
            "source_url": sources.get(subj, {}).get("url"),
            "retrieval_date": RETRIEVAL_DATE,
            "revision_id": None,
            "temporal_context": TEMPORAL,
        }

    OUT.mkdir(parents=True, exist_ok=True)

    def dump_jsonl(path, items):
        path.write_text(
            "".join(json.dumps(x, ensure_ascii=False) + "\n" for x in items), encoding="utf-8"
        )

    main_blind = [blind(r, f"F{i+1:03d}") for i, r in enumerate(main_ids)]
    pilot_blind = [blind(r, f"P{i+1:03d}") for i, r in enumerate(pilot_ids)]
    dump_jsonl(OUT / "factscore_80_blind.jsonl", main_blind)
    dump_jsonl(OUT / "pilot_12_claims.jsonl", pilot_blind)

    mapping = {}
    for rec, b in zip(main_ids + pilot_ids, main_blind + pilot_blind, strict=True):
        mapping[b["blind_id"]] = {
            "pid": rec["pid"],
            "claim_index": rec["claim_index"],
            "subject": rec["subject"],
            "frequency_score": rec["score"],
            "factscore_annotation": rec["_annotation"],
            "evidence_chars": len(b["evidence_text"]),
        }
    (OUT / "private_id_mapping.json").write_text(
        json.dumps(mapping, ensure_ascii=False, indent=1), encoding="utf-8"
    )

    manifest = {
        "seed": SEED,
        "rng": "python random.Random(seed), shuffle per stratum over (pid, claim_index) sorted",
        "created": "2026-11-17",
        "source_claims_file": "third_party/conformal-factual-lm/out/factscore_subclaims_with_scores.jsonl",
        "source_split_file": "data/splits/factscore.json",
        "sampling_depends_on_labels": False,
        "strata": {
            name: {
                "definition": name,
                "available_in_test": sum(1 for r in rows if STRATA[name](r["score"])),
                "selected_main": 20,
                "selected_pilot": 3,
            }
            for name in STRATA
        },
        "main_package": {"n": len(main_blind), "ids": "F001..F080"},
        "pilot_package": {
            "n": len(pilot_blind),
            "ids": "P001..P012",
            "pool": "all 50 biographies (the test split holds only 21 score-0 claims)",
            "disjoint_from_main": True,
            "purpose": "protocol adherence only; not a population sample",
        },
        "withheld_from_evaluator": [
            "factscore annotation (Y/S/N/U)",
            "frequency score",
            "tie-break noise term",
            "previous LLM grounded labels",
            "any prior judgment or expected result",
        ],
    }
    (OUT / "selection_manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=1), encoding="utf-8"
    )

    dump_jsonl(OUT / "source_manifest.jsonl", [sources[s] for s in sorted(sources)])

    schema = {
        "$schema": "http://json-schema.org/draft-07/schema#",
        "title": "evidence adjudication record",
        "type": "object",
        "required": ["blind_id", "state", "explanation", "quotes", "claim_parts",
                     "confidence", "complete_proposition", "temporal_caveat"],
        "properties": {
            "blind_id": {"type": "string"},
            "state": {"enum": ["supported", "contradicted", "unknown"]},
            "explanation": {"type": "string", "maxLength": 400},
            "quotes": {"type": "array", "items": {"type": "string"}},
            "claim_parts": {
                "type": "object",
                "required": ["supported", "contradicted", "unaddressed"],
                "properties": {
                    "supported": {"type": "array", "items": {"type": "string"}},
                    "contradicted": {"type": "array", "items": {"type": "string"}},
                    "unaddressed": {"type": "array", "items": {"type": "string"}},
                },
            },
            "confidence": {"enum": ["high", "medium", "low"]},
            "complete_proposition": {"type": "boolean"},
            "temporal_caveat": {"type": "string"},
        },
        "additionalProperties": False,
    }
    (OUT / "adjudication_schema.json").write_text(
        json.dumps(schema, ensure_ascii=False, indent=1), encoding="utf-8"
    )

    sizes = {p.name: p.stat().st_size for p in sorted(OUT.glob("*")) if p.is_file()}
    print("built:", json.dumps(sizes, indent=1))
    print("claims per stratum (main+pilot):",
          {k: sum(1 for r in main_ids if STRATA[k](r["score"])) for k in STRATA})
    print("evidence chars: total %d, max %d" % (
        sum(len(b["evidence_text"]) for b in main_blind),
        max(len(b["evidence_text"]) for b in main_blind)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
